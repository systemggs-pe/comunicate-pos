CREATE TABLE "CompanySettings" (
 "id" INTEGER NOT NULL DEFAULT 1 PRIMARY KEY CHECK ("id" = 1),
 "businessName" VARCHAR(100) NOT NULL,
 "businessType" VARCHAR(150) NOT NULL DEFAULT '',
 "address" VARCHAR(300) NOT NULL DEFAULT '',
 "city" VARCHAR(100) NOT NULL DEFAULT '',
 "phone" VARCHAR(30) NOT NULL DEFAULT '',
 "email" VARCHAR(254) NOT NULL DEFAULT '',
 "receiptFooter" VARCHAR(500) NOT NULL DEFAULT '',
 "defaultFormat" INTEGER CHECK ("defaultFormat" IN (48,80)),
 "margin48" DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK ("margin48" BETWEEN 0 AND 5),
 "margin80" DOUBLE PRECISION NOT NULL DEFAULT 2 CHECK ("margin80" BETWEEN 0 AND 10),
 "showClientContact" BOOLEAN NOT NULL DEFAULT TRUE,
 "showSerial" BOOLEAN NOT NULL DEFAULT TRUE,
 "showSeller" BOOLEAN NOT NULL DEFAULT TRUE,
 "updatedAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "updatedById" UUID REFERENCES "User"("id") ON DELETE SET NULL
);
